-- (a) Database and Seed Data [6 marks]
--     - Positive room capacities (capacity > 0)
--     - Status restricted to 'ACTIVE' or 'ENDED'
--     - Status/date consistency enforced via CHECK:
--       (status = 'ACTIVE' AND released_on IS NULL)
--       OR (status = 'ENDED' AND released_on IS NOT NULL AND released_on >= allocated_on)
--     - Seed data showing FULL, PARTLY OCCUPIED, and EMPTY rooms
--       (including Room R-104 with literally zero rows in allocations)
-- ============================================================================

CREATE TABLE students (
    student_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number VARCHAR(20)  NOT NULL UNIQUE,
    full_name      VARCHAR(100) NOT NULL
);

CREATE TABLE rooms (
    room_id     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number VARCHAR(20) NOT NULL UNIQUE,
    capacity    INT         NOT NULL CHECK (capacity > 0)
);

CREATE TABLE allocations (
    allocation_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id    INT         NOT NULL REFERENCES students(student_id),
    room_id       INT         NOT NULL REFERENCES rooms(room_id),
    allocated_on  DATE        NOT NULL,
    released_on   DATE        NULL,
    status        VARCHAR(10) NOT NULL CHECK (status IN ('ACTIVE', 'ENDED')),
    CONSTRAINT chk_allocations_status_dates CHECK (
        (status = 'ACTIVE' AND released_on IS NULL)
        OR (status = 'ENDED' AND released_on IS NOT NULL AND released_on >= allocated_on)
    )
);

CREATE TABLE occupancy_snapshot (
    snapshot_date DATE NOT NULL,
    room_id       INT  NOT NULL REFERENCES rooms(room_id),
    occupied_beds INT  NOT NULL CHECK (occupied_beds >= 0),
    free_beds     INT  NOT NULL CHECK (free_beds >= 0),
    PRIMARY KEY (snapshot_date, room_id)
);

