-- ============================================================================
-- (d) Trigger: BEFORE INSERT OR UPDATE row trigger on allocations [8 marks]
--     Enforces room capacity and single ACTIVE allocation per student for
--     direct SQL changes whenever NEW.status = 'ACTIVE'.
--     Excludes the row being updated when counting other allocations:
--     (TG_OP = 'INSERT' OR allocation_id <> NEW.allocation_id).
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_trg_enforce_allocation_rules()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity       INT;
    v_active_in_room INT;
BEGIN
    IF NEW.status = 'ACTIVE' THEN
        -- Lock target room row to prevent concurrent over-allocation
        SELECT r.capacity
          INTO v_capacity
          FROM rooms r
         WHERE r.room_id = NEW.room_id
           FOR UPDATE;

        IF NOT FOUND THEN
            RAISE EXCEPTION 'Room ID % does not exist.', NEW.room_id;
        END IF;

        -- Enforce at most one ACTIVE allocation per student (exclude self on UPDATE)
        IF EXISTS (
            SELECT 1
              FROM allocations a
             WHERE a.student_id = NEW.student_id
               AND a.status = 'ACTIVE'
               AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id)
        ) THEN
            RAISE EXCEPTION 'Trigger prevented SQL change: Student % already has an ACTIVE allocation.', NEW.student_id;
        END IF;

        -- Enforce room capacity (exclude self on UPDATE)
        SELECT COUNT(*)::INT
          INTO v_active_in_room
          FROM allocations a
         WHERE a.room_id = NEW.room_id
           AND a.status = 'ACTIVE'
           AND (TG_OP = 'INSERT' OR a.allocation_id <> NEW.allocation_id);

        IF v_active_in_room >= v_capacity THEN
            RAISE EXCEPTION 'Trigger prevented SQL change: Room % is at full capacity (% beds).', NEW.room_id, v_capacity;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_enforce_allocation_rules
BEFORE INSERT OR UPDATE ON allocations
FOR EACH ROW
EXECUTE FUNCTION fn_trg_enforce_allocation_rules();

