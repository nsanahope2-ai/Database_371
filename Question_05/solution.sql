-- ============================================================================
-- (c) Procedure: pr_allocate_room(p_student_id, p_room_id, p_allocated_on) [8 marks]
--     - Validates student_id, room_id, and non-null allocated_on
--     - Locks student & room rows FOR UPDATE for concurrency safety
--     - Ensures student has no ACTIVE allocation
--     - Checks availability via fn_free_beds(p_room_id) > 0
--     - Inserts one ACTIVE allocation with released_on = NULL
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_allocate_room(
    p_student_id   INT,
    p_room_id      INT,
    p_allocated_on DATE
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_student_id IS NULL THEN
        RAISE EXCEPTION 'p_student_id cannot be NULL.';
    END IF;

    IF p_room_id IS NULL THEN
        RAISE EXCEPTION 'p_room_id cannot be NULL.';
    END IF;

    IF p_allocated_on IS NULL THEN
        RAISE EXCEPTION 'p_allocated_on date cannot be NULL.';
    END IF;

    -- Validate student exists and lock student row
    PERFORM 1
       FROM students
      WHERE student_id = p_student_id
        FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown student_id: % does not exist.', p_student_id;
    END IF;

    -- Validate room exists and lock room row before checking bed availability
    PERFORM 1
       FROM rooms
      WHERE room_id = p_room_id
        FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown room_id: % does not exist.', p_room_id;
    END IF;

    -- Ensure the student has no ACTIVE allocation
    IF EXISTS (
        SELECT 1
          FROM allocations
         WHERE student_id = p_student_id
           AND status = 'ACTIVE'
    ) THEN
        RAISE EXCEPTION 'Student % already has an ACTIVE hostel allocation.', p_student_id;
    END IF;

    -- Check room bed availability
    IF fn_free_beds(p_room_id) <= 0 THEN
        RAISE EXCEPTION 'Room % is full; no free beds available.', p_room_id;
    END IF;

    -- Create one ACTIVE allocation with released_on NULL
    INSERT INTO allocations (student_id, room_id, allocated_on, released_on, status)
    VALUES (p_student_id, p_room_id, p_allocated_on, NULL, 'ACTIVE');
END;
$$;

