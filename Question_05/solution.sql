-- ============================================================================
-- (e) View: v_room_occupancy [5 marks]
--     Shows every room (room_id, room_number, capacity, occupied_beds, free_beds),
--     including rooms with no allocations (R-104) and rooms with only ENDED rows (R-103).
-- ============================================================================

CREATE OR REPLACE VIEW v_room_occupancy AS
SELECT
    r.room_id,
    r.room_number,
    r.capacity,
    COUNT(a.allocation_id)::INT                AS occupied_beds,
    (r.capacity - COUNT(a.allocation_id))::INT AS free_beds
FROM rooms r
LEFT JOIN allocations a
  ON a.room_id = r.room_id
 AND a.status = 'ACTIVE'
GROUP BY r.room_id, r.room_number, r.capacity;

-- Query the view
SELECT *
  FROM v_room_occupancy
 ORDER BY room_id;


