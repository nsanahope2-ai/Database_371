-- ============================================================================
-- (g) Scheduled Job: pr_refresh_occupancy() & Daily 23:55 Schedule [6 marks]
--     Stores CURRENT_DATE occupancy for every room (including empty rooms)
--     in occupancy_snapshot using one row per (snapshot_date, room_id) and
--     replaces values when rerun (ON CONFLICT DO UPDATE).
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_refresh_occupancy()
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO occupancy_snapshot (snapshot_date, room_id, occupied_beds, free_beds)
    SELECT
        CURRENT_DATE,
        r.room_id,
        COUNT(a.allocation_id)::INT                AS occupied_beds,
        (r.capacity - COUNT(a.allocation_id))::INT AS free_beds
    FROM rooms r
    LEFT JOIN allocations a
      ON a.room_id = r.room_id
     AND a.status = 'ACTIVE'
    GROUP BY r.room_id, r.capacity
    ON CONFLICT (snapshot_date, room_id)
    DO UPDATE SET
        occupied_beds = EXCLUDED.occupied_beds,
        free_beds     = EXCLUDED.free_beds;
END;
$$;

