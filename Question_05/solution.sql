-- ============================================================================
-- (b) Function: fn_free_beds(p_room_id) [6 marks]
--     Returns room capacity minus ACTIVE allocation count.
--     Rejects unknown/NULL room with RAISE EXCEPTION.
--     ENDED allocations do not reduce availability.
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id INT)
RETURNS INT
LANGUAGE plpgsql
AS $$
DECLARE
    v_capacity     INT;
    v_active_count INT;
BEGIN
    IF p_room_id IS NULL THEN
        RAISE EXCEPTION 'Room ID cannot be NULL.';
    END IF;

    SELECT r.capacity
      INTO v_capacity
      FROM rooms r
     WHERE r.room_id = p_room_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Unknown room_id: % does not exist.', p_room_id;
    END IF;

    SELECT COUNT(*)::INT
      INTO v_active_count
      FROM allocations a
     WHERE a.room_id = p_room_id
       AND a.status = 'ACTIVE';

    RETURN v_capacity - v_active_count;
END;
$$;

