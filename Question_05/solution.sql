-- (f) Index: Partial index supporting ACTIVE allocations filtered by room_id [5 marks]
--     Justification:
--       fn_free_beds(), trigger capacity checks, and active room roster queries
--       repeatedly filter WHERE room_id = ? AND status = 'ACTIVE'. As historical
--       'ENDED' allocations accumulate over academic years, they dominate the
--       table. A partial B-tree index on (room_id) WHERE status = 'ACTIVE'
--       indexes ONLY currently active beds, keeping the index tiny, avoiding
--       index maintenance overhead on ENDED history rows, and directly satisfying
--       the room_id + status = 'ACTIVE' predicate.
-- ============================================================================

CREATE INDEX idx_allocations_room_active
    ON allocations (room_id)
 WHERE status = 'ACTIVE';

