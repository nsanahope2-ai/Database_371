-- ============================================================================
-- (a) Database and Seed Data [6 marks]
--     Tables: customers, readings, bills, receivable_snapshot
--     Constraints:
--       - Non-negative numeric meter values (NUMERIC(10,2) CHECK >= 0)
--       - Month-start reading_month (reading_month = date_trunc('month', reading_month)::date)
--       - Unique (customer_id, reading_month) on readings
--       - Unique reading_id FK on bills (one bill per reading)
--       - charge >= 0, and amount_paid between 0 and charge
--     Note: Seed customers are inserted here; the 6 seed readings and bills are
--     inserted immediately after (b), (c), and (d) are created so that every
--     reading is validated by trigger (d) and every bill is generated via
--     procedure (c).
-- ============================================================================

CREATE TABLE customers (
    customer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR(120) NOT NULL CHECK (btrim(full_name) <> '')
);

CREATE TABLE readings (
    reading_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id      INTEGER NOT NULL REFERENCES customers(customer_id) ON DELETE RESTRICT,
    reading_month    DATE NOT NULL
                     CHECK (reading_month = date_trunc('month', reading_month)::date),
    previous_reading NUMERIC(10,2) NOT NULL CHECK (previous_reading >= 0),
    current_reading  NUMERIC(10,2) NOT NULL CHECK (current_reading >= 0),
    CONSTRAINT uq_readings_customer_month UNIQUE (customer_id, reading_month)
);

CREATE TABLE bills (
    bill_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reading_id  INTEGER NOT NULL UNIQUE REFERENCES readings(reading_id) ON DELETE RESTRICT,
    charge      NUMERIC(10,2) NOT NULL CHECK (charge >= 0),
    amount_paid NUMERIC(10,2) NOT NULL DEFAULT 0.00
                CHECK (amount_paid >= 0 AND amount_paid <= charge),
    due_on      DATE NOT NULL
);

CREATE TABLE receivable_snapshot (
    snapshot_date DATE PRIMARY KEY,
    total_due     NUMERIC(12,2) NOT NULL CHECK (total_due >= 0)
);

