        EXCEPTION WHEN OTHERS THEN
            RAISE NOTICE 'pg_cron extension not active (%): schedule CALL q07_water_billing.pr_refresh_receivables() at 00:30 daily via OS scheduler / pgAgent.', SQLERRM;
        END;
    ELSE
        RAISE NOTICE 'pg_cron is not installed on this Windows PostgreSQL 18.6 server; schedule CALL q07_water_billing.pr_refresh_receivables() daily at 00:30 (cron: 30 0 * * *) via Windows Task Scheduler or pgAgent.';
    END IF;
END;
$$;
