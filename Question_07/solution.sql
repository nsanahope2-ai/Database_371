    END;
END;
$$;

-- ============================================================================
-- (c) Procedure: pr_generate_bill(p_reading_id INTEGER, p_due_on DATE) [8 marks]
--     - Locks reading row FOR UPDATE
--     - Rejects NULL/unknown reading_id, NULL due_on, or duplicate bill
--     - Derives consumption = current_reading - previous_reading
--     - Calls fn_water_charge and inserts bill with amount_paid = 0.00
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_generate_bill(
    p_reading_id INTEGER,
    p_due_on     DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_prev        NUMERIC(10,2);
    v_curr        NUMERIC(10,2);
    v_consumption NUMERIC(10,2);
    v_charge      NUMERIC(10,2);
BEGIN
    IF p_reading_id IS NULL THEN
        RAISE EXCEPTION 'Reading ID must not be NULL.';
    END IF;

    IF p_due_on IS NULL THEN
        RAISE EXCEPTION 'Bill due date (p_due_on) must not be NULL.';
    END IF;

    -- Lock the target reading row to prevent concurrent duplicate billing
    SELECT previous_reading, current_reading
    INTO v_prev, v_curr
    FROM readings
    WHERE reading_id = p_reading_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Reading ID % does not exist.', p_reading_id;
    END IF;

    IF EXISTS (SELECT 1 FROM bills WHERE reading_id = p_reading_id) THEN
        RAISE EXCEPTION 'A bill already exists for reading ID %.', p_reading_id;
    END IF;

    v_consumption := v_curr - v_prev;
    v_charge      := fn_water_charge(v_consumption);

    INSERT INTO bills (reading_id, charge, amount_paid, due_on)
    VALUES (p_reading_id, v_charge, 0.00, p_due_on);
END;
$$;

-- ============================================================================
-- (d) Trigger: BEFORE INSERT OR UPDATE row trigger on readings [8 marks]
--     Rejects negative meter values and current_reading < previous_reading,
--     including direct SQL imports/updates. Rejected readings are never stored.
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_trg_validate_reading()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.previous_reading IS NULL OR NEW.current_reading IS NULL THEN
        RAISE EXCEPTION 'Meter readings cannot be NULL.';
    END IF;

    IF NEW.previous_reading < 0 OR NEW.current_reading < 0 THEN
        RAISE EXCEPTION 'Meter readings must be non-negative (previous=%, current=%).',
            NEW.previous_reading, NEW.current_reading;
    END IF;

    IF NEW.current_reading < NEW.previous_reading THEN
        RAISE EXCEPTION 'Invalid meter reading for customer % in %: current_reading (%) is less than previous_reading (%).',
            NEW.customer_id, NEW.reading_month, NEW.current_reading, NEW.previous_reading;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_readings_validate
BEFORE INSERT OR UPDATE ON readings
FOR EACH ROW
EXECUTE FUNCTION fn_trg_validate_reading();

