-- ============================================================================
-- (b) Function: fn_water_charge(p_units NUMERIC) [6 marks]
--     Tariff rules:
--       - Reject NULL or negative consumption
--       - 0 units -> K0.00
--       - First 10 units (0 <= p_units <= 10) -> K5.00 per unit
--       - Units above 10 (p_units > 10) -> (10 * K5.00) + ((p_units - 10) * K8.00)
--       - Return exact two-decimal charge NUMERIC(10,2)
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(10,2)
LANGUAGE plpgsql
IMMUTABLE
AS $$
DECLARE
    v_charge NUMERIC(10,2);
BEGIN
    IF p_units IS NULL OR p_units < 0 THEN
        RAISE EXCEPTION 'Invalid water consumption (%): units must be non-null and non-negative.', p_units;
    END IF;

    IF p_units = 0 THEN
        v_charge := 0.00;
    ELSIF p_units <= 10 THEN
        v_charge := ROUND(p_units * 5.00, 2)::NUMERIC(10,2);
    ELSE
        v_charge := ROUND((10 * 5.00) + ((p_units - 10) * 8.00), 2)::NUMERIC(10,2);
    END IF;

    RETURN v_charge;
END;
$$;

