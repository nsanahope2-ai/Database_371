-- ============================================================================
-- (g) Scheduled Job: pr_refresh_receivables() [6 marks]
--     Stores today's (CURRENT_DATE) total unpaid bill balances in
--     receivable_snapshot, replacing the same date's total on a rerun
--     via ON CONFLICT (snapshot_date) DO UPDATE.
--     Scheduled daily at 00:30 ('30 0 * * *') via pg_cron (safely guarded).
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_refresh_receivables()
LANGUAGE plpgsql
AS $$
DECLARE
    v_total_due NUMERIC(12,2);
BEGIN
    SELECT COALESCE(SUM(charge - amount_paid), 0.00)::NUMERIC(12,2)
    INTO v_total_due
    FROM bills
    WHERE amount_paid < charge;

    INSERT INTO receivable_snapshot (snapshot_date, total_due)
    VALUES (CURRENT_DATE, v_total_due)
    ON CONFLICT (snapshot_date) DO UPDATE
        SET total_due = EXCLUDED.total_due;
END;
$$;

