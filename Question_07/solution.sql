-- ============================================================================
-- (e) View: v_overdue_bills [5 marks]
--     Shows customer name, due date, and outstanding amount where
--     due_on < CURRENT_DATE and bill is not fully paid (amount_paid < charge).
-- ============================================================================

CREATE OR REPLACE VIEW v_overdue_bills AS
SELECT
    c.full_name,
    b.due_on,
    (b.charge - b.amount_paid)::NUMERIC(10,2) AS outstanding_amount
FROM bills b
JOIN readings r  ON r.reading_id = b.reading_id
JOIN customers c ON c.customer_id = r.customer_id
WHERE b.due_on < CURRENT_DATE
  AND b.amount_paid < b.charge;

SELECT *
FROM v_overdue_bills
ORDER BY due_on, full_name;

