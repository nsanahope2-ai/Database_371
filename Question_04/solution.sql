CREATE TABLE patients (
    patient_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(full_name)) > 0),
    phone         VARCHAR(30)  NULL,
    date_of_birth DATE         NULL
);

CREATE TABLE doctors (
    doctor_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(full_name)) > 0)
);

CREATE TABLE appointments (
    appointment_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      INT NOT NULL REFERENCES patients(patient_id) ON DELETE RESTRICT,
    doctor_id       INT NOT NULL REFERENCES doctors(doctor_id) ON DELETE RESTRICT,
    appointment_day DATE NOT NULL,
    slot_time       TIME NOT NULL,
    status          VARCHAR(20) NOT NULL,
    CONSTRAINT chk_appointments_valid_slot
        CHECK (slot_time IN (TIME '09:00', TIME '10:00', TIME '11:00', TIME '12:00')),
    CONSTRAINT chk_appointments_valid_status
        CHECK (status IN ('BOOKED', 'ATTENDED', 'CANCELLED'))
);

CREATE TABLE clinic_summary (
    summary_date    DATE PRIMARY KEY,
    booked_count    INTEGER NOT NULL CHECK (booked_count >= 0),
    attended_count  INTEGER NOT NULL CHECK (attended_count >= 0),
    cancelled_count INTEGER NOT NULL CHECK (cancelled_count >= 0)
);

