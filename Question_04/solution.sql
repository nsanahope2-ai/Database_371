-- ============================================================================
-- (d) Trigger: Reject Non-Cancelled Slot Clashes [8 marks]
-- BEFORE INSERT OR UPDATE row trigger on appointments.
-- Whenever NEW.status <> 'CANCELLED', checks for any other non-cancelled row
-- matching (doctor_id, appointment_day, slot_time), excluding the row being
-- updated itself via (TG_OP = 'INSERT' OR a.appointment_id <> NEW.appointment_id).
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_trg_prevent_slot_clash()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_conflict_id INT;
BEGIN
    -- A CANCELLED appointment never occupies an active slot
    IF NEW.status = 'CANCELLED' THEN
        RETURN NEW;
    END IF;

    -- Serialize concurrent writes for the same doctor
    PERFORM 1
      FROM doctors
     WHERE doctor_id = NEW.doctor_id
       FOR UPDATE;

    SELECT a.appointment_id
      INTO v_conflict_id
      FROM appointments a
     WHERE a.doctor_id = NEW.doctor_id
       AND a.appointment_day = NEW.appointment_day
       AND a.slot_time = NEW.slot_time
       AND a.status <> 'CANCELLED'
       AND (TG_OP = 'INSERT' OR a.appointment_id <> NEW.appointment_id)
     LIMIT 1;

    IF v_conflict_id IS NOT NULL THEN
        RAISE EXCEPTION
            'Slot clash: Doctor % already has a non-cancelled appointment (ID %) on % at %.',
            NEW.doctor_id, v_conflict_id, NEW.appointment_day, NEW.slot_time;
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_appointments_prevent_clash
BEFORE INSERT OR UPDATE ON appointments
FOR EACH ROW
EXECUTE FUNCTION fn_trg_prevent_slot_clash();

