-- ============================================================================
-- (g) Scheduled Job: pr_refresh_clinic_summary(p_day) [6 marks]
-- Counts BOOKED, ATTENDED, and CANCELLED appointments for p_day in clinic_summary.
-- Reruns replace that date's summary cleanly via ON CONFLICT (summary_date) DO UPDATE.
-- Scheduled daily at 01:00 for the previous day (CURRENT_DATE - 1).
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_refresh_clinic_summary(p_day DATE)
LANGUAGE plpgsql
AS $$
DECLARE
    v_booked    INTEGER;
    v_attended  INTEGER;
    v_cancelled INTEGER;
BEGIN
    IF p_day IS NULL THEN
        RAISE EXCEPTION 'Summary date (p_day) cannot be NULL.';
    END IF;

    SELECT COUNT(*) FILTER (WHERE status = 'BOOKED')::INTEGER,
           COUNT(*) FILTER (WHERE status = 'ATTENDED')::INTEGER,
           COUNT(*) FILTER (WHERE status = 'CANCELLED')::INTEGER
      INTO v_booked, v_attended, v_cancelled
      FROM appointments
     WHERE appointment_day = p_day;

    INSERT INTO clinic_summary (summary_date, booked_count, attended_count, cancelled_count)
    VALUES (p_day, v_booked, v_attended, v_cancelled)
    ON CONFLICT (summary_date) DO UPDATE
        SET booked_count    = EXCLUDED.booked_count,
            attended_count  = EXCLUDED.attended_count,
            cancelled_count = EXCLUDED.cancelled_count;
END;
$$;

-- Execute twice for CURRENT_DATE - 1 (scheduled target) and once for CURRENT_DATE
-- to verify accurate counts and idempotent replacement on rerun
CALL pr_refresh_clinic_summary(CURRENT_DATE - 1);
CALL pr_refresh_clinic_summary(CURRENT_DATE - 1);
CALL pr_refresh_clinic_summary(CURRENT_DATE);

SELECT * FROM clinic_summary ORDER BY summary_date;

-- Register daily schedule at 01:00 for previous day via pg_cron (guarded for
-- Windows PostgreSQL 18.6 where pg_cron is not bundled)
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
        PERFORM cron.schedule(
            'q04_daily_clinic_summary',
            '0 1 * * *',
            'CALL q04_clinic.pr_refresh_clinic_summary(CURRENT_DATE - 1);'
        );
        RAISE NOTICE 'Scheduled pg_cron job q04_daily_clinic_summary (0 1 * * *).';
    ELSE
        RAISE NOTICE 'pg_cron is not installed on this Windows PostgreSQL 18.6 server; cron.schedule(0 1 * * *) documented and guarded.';
    END IF;
END;
$$;
