-- (e) View: v_today_appointments [5 marks]
-- Shows today's BOOKED appointments with ONLY patient name, doctor name, and
-- slot_time. Unrelated patient data (patient_id, phone, date_of_birth) is not exposed.
-- ============================================================================

CREATE OR REPLACE VIEW v_today_appointments AS
SELECT p.full_name AS patient_name,
       d.full_name AS doctor_name,
       a.slot_time
  FROM appointments a
  JOIN patients p ON p.patient_id = a.patient_id
  JOIN doctors d  ON d.doctor_id  = a.doctor_id
 WHERE a.appointment_day = CURRENT_DATE
   AND a.status = 'BOOKED';

SELECT * FROM v_today_appointments ORDER BY slot_time, doctor_name;

-- ============================================================================
-- (f) Non-Unique Composite Index on (appointment_day, doctor_id) [5 marks]
-- Justification:
--   1. Non-unique: Each doctor has up to four active slots per day (09:00-12:00)
--      plus potential CANCELLED rows on the same date, so multiple rows share
--      (appointment_day, doctor_id). A UNIQUE index would falsely block 2nd-4th
--      daily bookings for a doctor.
--   2. Column order (appointment_day, doctor_id): Directly satisfies equality
--      lookups on both columns (fn_daily_load, doctor daily rosters, clash checks)
--      and, by the B-tree leftmost-prefix rule, also supports date-only filters
--      such as v_today_appointments and pr_refresh_clinic_summary(p_day).
-- ============================================================================

CREATE INDEX idx_appointments_day_doctor
    ON appointments (appointment_day, doctor_id);

