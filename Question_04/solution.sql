-- ============================================================================
-- (b) Function: fn_daily_load(p_doctor_id, p_day) [6 marks]
-- Returns the count of non-cancelled appointments for p_doctor_id on p_day.
-- Rejects NULL inputs or an unknown doctor; returns 0 when no bookings exist.
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_daily_load(
    p_doctor_id INT,
    p_day       DATE
)
RETURNS INTEGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_load INTEGER;
BEGIN
    IF p_doctor_id IS NULL THEN
        RAISE EXCEPTION 'Doctor ID (p_doctor_id) cannot be NULL.';
    END IF;

    IF p_day IS NULL THEN
        RAISE EXCEPTION 'Appointment day (p_day) cannot be NULL.';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM doctors WHERE doctor_id = p_doctor_id) THEN
        RAISE EXCEPTION 'Doctor ID % does not exist.', p_doctor_id;
    END IF;

    SELECT COUNT(*)::INTEGER
      INTO v_load
      FROM appointments
     WHERE doctor_id = p_doctor_id
       AND appointment_day = p_day
       AND status <> 'CANCELLED';

    RETURN v_load;
END;
$$;

-- Verify fn_daily_load:
--   Doctor 1 yesterday: 2 ATTENDED + 1 CANCELLED -> load = 2
--   Doctor 1 today:     1 BOOKED + 1 ATTENDED    -> load = 2
--   Doctor 3 today:     no appointments          -> load = 0
SELECT d.doctor_id,
       d.full_name,
       fn_daily_load(d.doctor_id, CURRENT_DATE - 1) AS load_yesterday,
       fn_daily_load(d.doctor_id, CURRENT_DATE)     AS load_today
  FROM doctors d
 ORDER BY d.doctor_id;

-- Verify rejection of unknown doctor
DO $$
BEGIN
    PERFORM fn_daily_load(999, CURRENT_DATE);
    RAISE EXCEPTION 'Expected fn_daily_load(999, CURRENT_DATE) to fail!';
EXCEPTION
    WHEN OTHERS THEN
        RAISE NOTICE '[PASS] Unknown doctor rejected by fn_daily_load: %', SQLERRM;
END;
$$;

-- ============================================================================
-- (c) Procedure: pr_book_appointment(p_patient_id, p_doctor_id, p_day, p_slot) [8 marks]
-- Validates patient and doctor existence, rejects past dates and unsupported
-- slots, and inserts a new BOOKED appointment.
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_book_appointment(
    p_patient_id INT,
    p_doctor_id  INT,
    p_day        DATE,
    p_slot       TIME
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_patient_id IS NULL OR p_doctor_id IS NULL OR p_day IS NULL OR p_slot IS NULL THEN
        RAISE EXCEPTION 'All booking parameters (patient, doctor, day, slot) must be non-NULL.';
    END IF;

    IF NOT EXISTS (SELECT 1 FROM patients WHERE patient_id = p_patient_id) THEN
        RAISE EXCEPTION 'Patient ID % does not exist.', p_patient_id;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM doctors WHERE doctor_id = p_doctor_id) THEN
        RAISE EXCEPTION 'Doctor ID % does not exist.', p_doctor_id;
    END IF;

    IF p_day < CURRENT_DATE THEN
        RAISE EXCEPTION 'Cannot book appointment in the past (% < %).', p_day, CURRENT_DATE;
    END IF;

    IF p_slot NOT IN (TIME '09:00', TIME '10:00', TIME '11:00', TIME '12:00') THEN
        RAISE EXCEPTION 'Unsupported slot %. Allowed clinic slots are 09:00, 10:00, 11:00, and 12:00.', p_slot;
    END IF;

    INSERT INTO appointments (patient_id, doctor_id, appointment_day, slot_time, status)
    VALUES (p_patient_id, p_doctor_id, p_day, p_slot, 'BOOKED');
END;
$$;

