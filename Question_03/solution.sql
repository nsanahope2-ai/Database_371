-- ============================================================================
-- (b) Function: fn_loan_fine(p_loan_id, p_as_of) [6 marks]
-- Returns K2.00 * overdue days (minimum K0.00).
-- Uses LEAST(p_as_of, returned_on) when returned_on IS NOT NULL so returned
-- loans stop accumulating fines after return. Rejects NULLs or unknown loans.
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_loan_fine(
    p_loan_id INT,
    p_as_of   DATE
)
RETURNS NUMERIC(10, 2)
LANGUAGE plpgsql
AS $$
DECLARE
    v_due_on         DATE;
    v_returned_on    DATE;
    v_effective_date DATE;
    v_overdue_days   INTEGER;
BEGIN
    IF p_loan_id IS NULL THEN
        RAISE EXCEPTION 'Loan ID (p_loan_id) cannot be NULL.';
    END IF;

    IF p_as_of IS NULL THEN
        RAISE EXCEPTION 'As-of date (p_as_of) cannot be NULL.';
    END IF;

    SELECT due_on, returned_on
      INTO v_due_on, v_returned_on
      FROM loans
     WHERE loan_id = p_loan_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan ID % does not exist.', p_loan_id;
    END IF;

    v_effective_date := CASE
        WHEN v_returned_on IS NOT NULL THEN LEAST(p_as_of, v_returned_on)
        ELSE p_as_of
    END;

    v_overdue_days := GREATEST(v_effective_date - v_due_on, 0);

    RETURN (v_overdue_days * 2.00)::NUMERIC(10, 2);
END;
$$;

