-- ============================================================================
-- (f) Partial Index for a Given Book's Unreturned Loans [5 marks]
-- Justification:
--   Most library loans over time are returned (returned_on IS NOT NULL), so a
--   full index on (book_id, returned_on) would grow continuously with historical
--   rows. A partial index WHERE returned_on IS NULL indexes ONLY active loans,
--   keeping the B-tree tiny, faster to scan, and free of index maintenance
--   overhead when historical returned rows are queried or archived.
-- ============================================================================

CREATE INDEX idx_loans_book_unreturned
    ON loans (book_id)
 WHERE returned_on IS NULL;

