-- ============================================================================
-- (g) Scheduled Job: pr_refresh_overdue(p_as_of) [6 marks]
-- Counts overdue loans still unreturned as of p_as_of and sums their fines as of
-- p_as_of. Replaces the same snapshot_date cleanly on rerun (idempotent UPSERT).
-- Scheduled daily at 00:10 for CURRENT_DATE.
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql
AS $$
DECLARE
    v_overdue_count INTEGER;
    v_total_fine    NUMERIC(12, 2);
BEGIN
    IF p_as_of IS NULL THEN
        RAISE EXCEPTION 'Snapshot date (p_as_of) cannot be NULL.';
    END IF;

    SELECT COUNT(*)::INTEGER,
           COALESCE(SUM(fn_loan_fine(l.loan_id, p_as_of)), 0.00)::NUMERIC(12, 2)
      INTO v_overdue_count, v_total_fine
      FROM loans l
     WHERE l.borrowed_on <= p_as_of
       AND l.due_on < p_as_of
       AND (l.returned_on IS NULL OR l.returned_on > p_as_of);

    INSERT INTO overdue_summary (snapshot_date, overdue_count, total_fine)
    VALUES (p_as_of, v_overdue_count, v_total_fine)
    ON CONFLICT (snapshot_date) DO UPDATE
        SET overdue_count = EXCLUDED.overdue_count,
            total_fine    = EXCLUDED.total_fine;
END;
$$;

