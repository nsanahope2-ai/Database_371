-- ============================================================================
-- (c) Procedure: pr_return_loan(p_loan_id, p_returned_on) [8 marks]
-- Rejects unknown loan, already returned loan, NULL return date, and return
-- before borrowed_on. Stores returned_on and calculated final fine in one UPDATE.
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_return_loan(
    p_loan_id     INT,
    p_returned_on DATE
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_borrowed_on DATE;
    v_returned_on DATE;
    v_final_fine  NUMERIC(10, 2);
BEGIN
    IF p_loan_id IS NULL THEN
        RAISE EXCEPTION 'Loan ID (p_loan_id) cannot be NULL.';
    END IF;

    IF p_returned_on IS NULL THEN
        RAISE EXCEPTION 'Return date (p_returned_on) cannot be NULL for loan ID %.', p_loan_id;
    END IF;

    -- Lock target loan row to prevent concurrent double-return races
    SELECT borrowed_on, returned_on
      INTO v_borrowed_on, v_returned_on
      FROM loans
     WHERE loan_id = p_loan_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Loan ID % does not exist.', p_loan_id;
    END IF;

    IF v_returned_on IS NOT NULL THEN
        RAISE EXCEPTION 'Loan ID % has already been returned on %.', p_loan_id, v_returned_on;
    END IF;

    IF p_returned_on < v_borrowed_on THEN
        RAISE EXCEPTION 'Return date (%) cannot be earlier than borrowed_on (%) for loan ID %.',
            p_returned_on, v_borrowed_on, p_loan_id;
    END IF;

    -- Compute final fine as of p_returned_on before updating the row
    v_final_fine := fn_loan_fine(p_loan_id, p_returned_on);

    -- Persist returned_on and final fine together in a single atomic UPDATE
    UPDATE loans
       SET returned_on = p_returned_on,
           fine_amount = v_final_fine
     WHERE loan_id = p_loan_id;
END;
$$;

