CREATE TABLE books (
    book_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title   VARCHAR(200) NOT NULL CHECK (LENGTH(TRIM(title)) > 0)
);

CREATE TABLE loans (
    loan_id       INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id       INT NOT NULL REFERENCES books(book_id) ON DELETE RESTRICT,
    borrower_name VARCHAR(150) NOT NULL CHECK (LENGTH(TRIM(borrower_name)) > 0),
    borrowed_on   DATE NOT NULL,
    due_on        DATE NOT NULL,
    returned_on   DATE NULL,
    fine_amount   NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT chk_loans_due_after_borrowed
        CHECK (due_on >= borrowed_on),
    CONSTRAINT chk_loans_returned_after_borrowed
        CHECK (returned_on IS NULL OR returned_on >= borrowed_on),
    CONSTRAINT chk_loans_nonnegative_fine
        CHECK (fine_amount >= 0)
);

CREATE TABLE loan_audit (
    audit_id        INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id         INT NOT NULL REFERENCES loans(loan_id) ON DELETE CASCADE,
    old_returned_on DATE NULL,
    new_returned_on DATE NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE overdue_summary (
    snapshot_date DATE PRIMARY KEY,
    overdue_count INTEGER NOT NULL CHECK (overdue_count >= 0),
    total_fine    NUMERIC(12, 2) NOT NULL CHECK (total_fine >= 0)
);

