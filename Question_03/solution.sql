-- ============================================================================
-- (d) Trigger: Audit changes to returned_on in loan_audit [8 marks]
-- Logs OLD.returned_on and NEW.returned_on on AFTER UPDATE ONLY when
-- returned_on actually changes (OLD.returned_on IS DISTINCT FROM NEW.returned_on).
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_trg_audit_loan_return()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    INSERT INTO loan_audit (loan_id, old_returned_on, new_returned_on, changed_at)
    VALUES (NEW.loan_id, OLD.returned_on, NEW.returned_on, CURRENT_TIMESTAMP);

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_loans_audit_returned_on
AFTER UPDATE ON loans
FOR EACH ROW
WHEN (OLD.returned_on IS DISTINCT FROM NEW.returned_on)
EXECUTE FUNCTION fn_trg_audit_loan_return();

