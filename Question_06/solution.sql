-- ============================================================================
-- (a) Database and Seed Data [6 marks]
--     - Non-negative money inputs: NUMERIC(12,2) NOT NULL CHECK (... >= 0)
--     - BOOLEAN NOT NULL for active
--     - pay_month stored as first date of a month, enforced via CHECK:
--       pay_month = date_trunc('month', pay_month)::date
--     - Unique constraint on (employee_id, pay_month)
--     - Seed active and inactive employees (including an employee who was paid
--       in Month 1 and later became inactive) and data for two payroll months
-- ============================================================================

CREATE TABLE employees (
    employee_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name    VARCHAR(100)  NOT NULL,
    basic_salary NUMERIC(12,2) NOT NULL CHECK (basic_salary >= 0),
    allowance    NUMERIC(12,2) NOT NULL CHECK (allowance >= 0),
    deduction    NUMERIC(12,2) NOT NULL CHECK (deduction >= 0),
    active       BOOLEAN       NOT NULL DEFAULT TRUE
);

CREATE TABLE payroll (
    payroll_id  INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT           NOT NULL REFERENCES employees(employee_id),
    pay_month   DATE          NOT NULL CHECK (pay_month = date_trunc('month', pay_month)::date),
    gross_pay   NUMERIC(12,2) NOT NULL CHECK (gross_pay >= 0),
    net_pay     NUMERIC(12,2) NOT NULL CHECK (net_pay >= 0),
    CONSTRAINT uq_payroll_employee_month UNIQUE (employee_id, pay_month)
);

CREATE TABLE salary_audit (
    audit_id    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id INT           NOT NULL REFERENCES employees(employee_id),
    old_salary  NUMERIC(12,2) NOT NULL CHECK (old_salary >= 0),
    new_salary  NUMERIC(12,2) NOT NULL CHECK (new_salary >= 0),
    changed_at  TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

