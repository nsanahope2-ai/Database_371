-- ============================================================================
-- (f) Index: idx_payroll_pay_month ON payroll(pay_month) [5 marks]
--     Justification:
--       The table constraint UNIQUE (employee_id, pay_month) creates a composite
--       B-tree index with employee_id as the LEADING column and pay_month second.
--       A monthly report filtering WHERE pay_month = DATE '2026-01-01' across ALL
--       employees omits the leading column employee_id, so PostgreSQL cannot
--       perform a direct leading-key equality seek on uq_payroll_employee_month.
--       Creating a single-column index on (pay_month) alone places pay_month
--       first for direct B-tree lookups by month while avoiding duplicating the
--       existing (employee_id, pay_month) composite key.
-- ============================================================================

CREATE INDEX idx_payroll_pay_month
    ON payroll (pay_month);

ANALYZE payroll;

