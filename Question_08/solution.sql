-- ============================================================================
-- (a) Database and Seed Data [6 marks]
--     Tables: vehicles, trips, service_alerts
--     Constraints:
--       - Non-negative odometers (current_odometer >= 0, last_service_odometer >= 0,
--         start_odometer >= 0)
--       - last_service_odometer <= current_odometer
--       - end_odometer > start_odometer
--     Seed Data:
--       - 3 vehicles with distinct initial service positions inserted here.
--       - 6 trips added through pr_record_trip AFTER trigger (d) is installed.
-- ============================================================================

CREATE TABLE vehicles (
    vehicle_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration          VARCHAR(20) NOT NULL UNIQUE CHECK (btrim(registration) <> ''),
    current_odometer      INTEGER NOT NULL CHECK (current_odometer >= 0),
    last_service_odometer INTEGER NOT NULL CHECK (last_service_odometer >= 0),
    CONSTRAINT chk_vehicles_service_le_current
        CHECK (last_service_odometer <= current_odometer)
);

CREATE TABLE trips (
    trip_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id     INTEGER NOT NULL REFERENCES vehicles(vehicle_id) ON DELETE RESTRICT,
    trip_on        DATE NOT NULL,
    start_odometer INTEGER NOT NULL CHECK (start_odometer >= 0),
    end_odometer   INTEGER NOT NULL CHECK (end_odometer > start_odometer)
);

CREATE TABLE service_alerts (
    vehicle_id       INTEGER PRIMARY KEY REFERENCES vehicles(vehicle_id) ON DELETE CASCADE,
    km_since_service INTEGER NOT NULL CHECK (km_since_service >= 5000),
    flagged_on       DATE NOT NULL DEFAULT CURRENT_DATE
);

