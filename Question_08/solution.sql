-- ============================================================================
-- (b) Function: fn_service_due(p_vehicle_id INTEGER) [6 marks]
--     Returns BOOLEAN for the 5,000-kilometre rule:
--       (current_odometer - last_service_odometer) >= 5000
--     Rejects NULL or unknown vehicle ID with RAISE EXCEPTION.
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_service_due(p_vehicle_id INTEGER)
RETURNS BOOLEAN
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    v_current      INTEGER;
    v_last_service INTEGER;
BEGIN
    IF p_vehicle_id IS NULL THEN
        RAISE EXCEPTION 'Vehicle ID must not be NULL.';
    END IF;

    SELECT current_odometer, last_service_odometer
    INTO v_current, v_last_service
    FROM vehicles
    WHERE vehicle_id = p_vehicle_id;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', p_vehicle_id;
    END IF;

    RETURN (v_current - v_last_service) >= 5000;
END;
$$;

-- ============================================================================
-- (c) Procedure: pr_record_trip(p_vehicle_id, p_trip_on, p_start, p_end) [8 marks]
--     - Validates vehicle exists
--     - Requires non-null date and odometers, non-negative start, and p_end > p_start
--     - Inserts the trip ONLY; does NOT update vehicles.current_odometer
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_record_trip(
    p_vehicle_id INTEGER,
    p_trip_on    DATE,
    p_start      INTEGER,
    p_end        INTEGER
)
LANGUAGE plpgsql
AS $$
BEGIN
    IF p_vehicle_id IS NULL THEN
        RAISE EXCEPTION 'Vehicle ID must not be NULL.';
    END IF;

    IF p_trip_on IS NULL OR p_start IS NULL OR p_end IS NULL THEN
        RAISE EXCEPTION 'Trip date, start_odometer, and end_odometer must all be non-null.';
    END IF;

    IF p_start < 0 THEN
        RAISE EXCEPTION 'Trip start_odometer (%) must be non-negative.', p_start;
    END IF;

    IF p_end <= p_start THEN
        RAISE EXCEPTION 'Trip end_odometer (%) must be strictly greater than start_odometer (%).',
            p_end, p_start;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM vehicles WHERE vehicle_id = p_vehicle_id) THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', p_vehicle_id;
    END IF;

    -- Insert trip only; odometer advancement is enforced and executed by trg_trips_before_insert
    INSERT INTO trips (vehicle_id, trip_on, start_odometer, end_odometer)
    VALUES (p_vehicle_id, p_trip_on, p_start, p_end);
END;
$$;

-- ============================================================================
-- (d) Trigger: BEFORE INSERT row trigger on trips [8 marks]
--     - Locks vehicles row FOR UPDATE
--     - Rejects NULL/invalid mileage (start < 0 or end <= start)
--     - Verifies NEW.start_odometer matches vehicles.current_odometer
--     - Updates vehicles.current_odometer to NEW.end_odometer exactly once
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_trg_trips_before_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_current_odo INTEGER;
BEGIN
    IF NEW.vehicle_id IS NULL OR NEW.trip_on IS NULL
       OR NEW.start_odometer IS NULL OR NEW.end_odometer IS NULL THEN
        RAISE EXCEPTION 'Trip vehicle_id, trip_on, start_odometer, and end_odometer cannot be NULL.';
    END IF;

    IF NEW.start_odometer < 0 OR NEW.end_odometer <= NEW.start_odometer THEN
        RAISE EXCEPTION 'Invalid trip mileage (start=%, end=%): require 0 <= start < end.',
            NEW.start_odometer, NEW.end_odometer;
    END IF;

    -- Lock parent vehicle row to serialize concurrent trip insertions
    SELECT current_odometer
    INTO v_current_odo
    FROM vehicles
    WHERE vehicle_id = NEW.vehicle_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Vehicle ID % does not exist.', NEW.vehicle_id;
    END IF;

    IF NEW.start_odometer <> v_current_odo THEN
        RAISE EXCEPTION 'Odometer continuity violation for vehicle %: trip start_odometer (%) does not match current_odometer (%).',
            NEW.vehicle_id, NEW.start_odometer, v_current_odo;
    END IF;

    -- Advance vehicle current_odometer exactly once
    UPDATE vehicles
    SET current_odometer = NEW.end_odometer
    WHERE vehicle_id = NEW.vehicle_id;

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_trips_before_insert
BEFORE INSERT ON trips
FOR EACH ROW
EXECUTE FUNCTION fn_trg_trips_before_insert();

