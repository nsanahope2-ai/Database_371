-- ============================================================================
-- (g) Scheduled Job: pr_refresh_service_alerts() [6 marks]
--     1. Removes alerts for vehicles no longer due (< 5,000 km since service)
--     2. Inserts or updates (ON CONFLICT DO UPDATE) one alert per due vehicle
--        (>= 5,000 km since service)
--     Scheduled every Monday at 06:00 ('0 6 * * 1') via pg_cron (safely guarded).
-- ============================================================================

CREATE OR REPLACE PROCEDURE pr_refresh_service_alerts()
LANGUAGE plpgsql
AS $$
BEGIN
    -- 1. Remove alerts for vehicles whose service has brought them below 5,000 km
    DELETE FROM service_alerts sa
    WHERE NOT EXISTS (
        SELECT 1
        FROM vehicles v
        WHERE v.vehicle_id = sa.vehicle_id
          AND (v.current_odometer - v.last_service_odometer) >= 5000
    );

    -- 2. Upsert one alert for every vehicle currently due (>= 5,000 km)
    INSERT INTO service_alerts (vehicle_id, km_since_service, flagged_on)
    SELECT
        v.vehicle_id,
        (v.current_odometer - v.last_service_odometer) AS km_since_service,
        CURRENT_DATE
    FROM vehicles v
    WHERE (v.current_odometer - v.last_service_odometer) >= 5000
    ON CONFLICT (vehicle_id) DO UPDATE
        SET km_since_service = EXCLUDED.km_since_service,
            flagged_on       = EXCLUDED.flagged_on;
END;
$$;

